function encode(text: string): boolean[] {
  const values: number[] = [CODE128_START_B];
  for (const ch of text) {
    const v = CODE128B[ch];
    if (v === undefined) return [];
    values.push(v);
  }
  let checksum = values[0];
  for (let i = 1; i < values.length; i++) checksum += values[i] * i;
  values.push(checksum % 103);
  values.push(CODE128_STOP);

  const bars: boolean[] = [];
  for (const v of values) {
    const p = PATTERNS[v];
    if (!p) return [];
    for (let i = 0; i < p.length; i++) {
      const on = i % 2 === 0;
      for (let j = 0; j < p[i]; j++) bars.push(on);
    }
  }
  return bars;
}

interface Props {
  value: string;
  height?: number;
  className?: string;
}

export function MemberBarcode({ value, height = 50, className = "" }: Props) {
  const bars = useMemo(() => encode(value), [value]);
  if (bars.length === 0) return null;
  const w = bars.length;

  return (
    <svg
      viewBox={`0 0 ${w} ${height}`}
      className={className}
      preserveAspectRatio="none"
      style={{ width: "100%", height }}
    >
      {bars.map((on, i) =>
        on ? <rect key={i} x={i} y={0} width={1} height={height} fill="currentColor" /> : null
      )}
    </svg>
  );
}
